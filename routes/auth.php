<?php

use App\Http\Controllers\Auth\AuthenticatedSessionController;
use Illuminate\Support\Facades\Route;

/*
|--------------------------------------------------------------------------
| Authentication Routes
| These are generated by Laravel Breeze. If Breeze is installed via
| `php artisan breeze:install blade`, this file will be auto-generated.
